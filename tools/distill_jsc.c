/* distill-jsc: compile JavaScript to QuickJS bytecode, as C arrays.

   A build tool, run on the build machine. The engine used to read linkedom
   and Readability from the source tree on every navigation, which tied every
   binary to a checkout and parsed 540 KB of JavaScript each time. Now they
   are compiled here, once, and linked in.

       distill-jsc OUT.c  SYMBOL module|script FILE NAME  [SYMBOL ... ]

   NAME is the file name the bytecode carries into stack traces: a logical
   name such as "linkedom/worker.js", never the path on this machine, so the
   output neither leaks nor depends on where the build ran.

   Bytecode belongs to the QuickJS it was made with. This tool links the same
   libqjs as the engine, so the two cannot disagree. */

#include <quickjs.h>

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static char *read_file(const char *path, size_t *length)
{
    FILE *file = fopen(path, "rb");
    if (!file) return NULL;
    size_t capacity = 1 << 16, used = 0;
    char *data = malloc(capacity + 1);
    size_t got;
    while (data && (got = fread(data + used, 1, capacity - used, file)) > 0) {
        used += got;
        if (used == capacity) {
            capacity *= 2;
            char *grown = realloc(data, capacity + 1);
            if (!grown) { free(data); data = NULL; }
            else data = grown;
        }
    }
    fclose(file);
    if (!data) return NULL;
    data[used] = '\0';
    *length = used;
    return data;
}

static void report(JSContext *context, const char *what)
{
    JSValue exception = JS_GetException(context);
    const char *text = JS_ToCString(context, exception);
    fprintf(stderr, "distill-jsc: %s: %s\n", what, text ? text : "unknown error");
    JS_FreeCString(context, text);
    JS_FreeValue(context, exception);
}

int main(int argc, char **argv)
{
    if (argc < 6 || (argc - 2) % 4 != 0) {
        fprintf(stderr, "usage: %s OUT.c SYMBOL module|script FILE NAME [...]\n", argv[0]);
        return 2;
    }
    FILE *out = fopen(argv[1], "w");
    if (!out) { fprintf(stderr, "distill-jsc: cannot write %s\n", argv[1]); return 2; }
    JSRuntime *runtime = JS_NewRuntime();
    JSContext *context = runtime ? JS_NewContext(runtime) : NULL;
    if (!context) { fprintf(stderr, "distill-jsc: no QuickJS context\n"); return 2; }
    fprintf(out, "/* Generated by distill-jsc. Do not edit. */\n\n"
                 "#include \"embedded_js.h\"\n");
    int status = 0;
    for (int i = 2; i < argc && !status; i += 4) {
        const char *symbol = argv[i], *kind = argv[i + 1], *path = argv[i + 2], *name = argv[i + 3];
        size_t length = 0;
        char *source = read_file(path, &length);
        if (!source) { fprintf(stderr, "distill-jsc: cannot read %s\n", path); status = 2; break; }
        int flags = JS_EVAL_FLAG_COMPILE_ONLY |
                    (strcmp(kind, "module") == 0 ? JS_EVAL_TYPE_MODULE : JS_EVAL_TYPE_GLOBAL);
        JSValue compiled = JS_Eval(context, source, length, name, flags);
        free(source);
        if (JS_IsException(compiled)) { report(context, path); status = 2; break; }
        size_t size = 0;
        uint8_t *bytes = JS_WriteObject(context, &size, compiled, JS_WRITE_OBJ_BYTECODE);
        JS_FreeValue(context, compiled);
        if (!bytes) { report(context, path); status = 2; break; }
        fprintf(out, "\nconst unsigned char %s[] = {", symbol);
        for (size_t at = 0; at < size; ++at)
            fprintf(out, "%s%u,", at % 24 ? "" : "\n    ", bytes[at]);
        fprintf(out, "\n};\nconst size_t %s_size = %zu;\n", symbol, size);
        js_free(context, bytes);
    }
    JS_FreeContext(context);
    JS_FreeRuntime(runtime);
    if (fclose(out) != 0) status = 2;
    if (status) remove(argv[1]);
    return status;
}
