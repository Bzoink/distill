#!/usr/bin/env python3
"""Generate src/cell_width.h: how many terminal cells a code point occupies.

The terminal renderer is a pure function of the reader page and a size, and
its output is gated. glibc's wcwidth() would make it a function of the locale
and the C library's Unicode version as well, so the table is generated here,
from Python's Unicode database, and checked in. Regenerate only on purpose:

    python3 tools/make_cell_width.py

Two range lists come out:

- zero width: combining and enclosing marks (Mn, Me), format characters (Cf)
  and the Hangul medial vowels and final consonants that join the syllable
  before them. These occupy no cell of their own; the grapheme iterator
  attaches them to the cluster they belong to.
- wide: East Asian Wide and Fullwidth, plus the regional indicators, which
  terminals draw two cells wide when they pair into a flag.

Everything else printable is one cell.
"""

import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "cell_width.h")


def ranges(predicate):
    out = []
    start = None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            hit = False
        else:
            hit = predicate(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def zero_width(cp):
    if 0x1160 <= cp <= 0x11FF or 0xD7B0 <= cp <= 0xD7FF:
        return True
    return unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf")


def wide(cp):
    if 0x1F1E6 <= cp <= 0x1F1FF:
        return True
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F") and not zero_width(cp)


def emit(name, table):
    lines = [f"static const DCellRange {name}[] = {{"]
    row = []
    for lo, hi in table:
        row.append(f"{{0x{lo:05x}, 0x{hi:05x}}}")
        if len(row) == 4:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    zero = ranges(zero_width)
    wide_ranges = ranges(wide)
    text = f"""/* Generated by tools/make_cell_width.py from Unicode {unicodedata.unidata_version}.
   Do not edit; regenerate. See that script for what the two lists mean. */
#ifndef DISTILL_CELL_WIDTH_H
#define DISTILL_CELL_WIDTH_H

#include <stdint.h>

typedef struct {{ uint32_t first; uint32_t last; }} DCellRange;

#define DISTILL_CELL_WIDTH_UNICODE "{unicodedata.unidata_version}"

{emit("d_cell_zero_width", zero)}

{emit("d_cell_wide", wide_ranges)}

static inline int d_cell_in(const DCellRange *table, size_t count, uint32_t cp)
{{
    size_t lo = 0, hi = count;
    while (lo < hi) {{
        size_t mid = (lo + hi) / 2;
        if (cp < table[mid].first) hi = mid;
        else if (cp > table[mid].last) lo = mid + 1;
        else return 1;
    }}
    return 0;
}}

/* Cells one code point occupies on its own: 0, 1 or 2. Control characters
   are 0 -- they have no business in a cell. */
static inline int d_cell_width(uint32_t cp)
{{
    if (cp < 0x20 || (cp >= 0x7f && cp < 0xa0)) return 0;
    if (cp < 0x300) return cp == 0xad ? 0 : 1;
    if (d_cell_in(d_cell_zero_width, sizeof(d_cell_zero_width) / sizeof(d_cell_zero_width[0]), cp))
        return 0;
    if (d_cell_in(d_cell_wide, sizeof(d_cell_wide) / sizeof(d_cell_wide[0]), cp))
        return 2;
    return 1;
}}

#endif
"""
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote {os.path.relpath(OUT)}: {len(zero)} zero-width ranges, "
          f"{len(wide_ranges)} wide ranges (Unicode {unicodedata.unidata_version})")


if __name__ == "__main__":
    sys.exit(main())
